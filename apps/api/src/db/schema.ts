/** The club chat. Deleted messages keep their row (replies still point to them) but lose their text. */
export const chatMessages = pgTable(
  'chat_messages',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    authorId: uuid('author_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    body: text('body').notNull(),
    replyToId: uuid('reply_to_id').references((): AnyPgColumn => chatMessages.id, { onDelete: 'set null' }),
    mentions: jsonb('mentions').$type<string[]>().notNull().default([]),
    deletedAt: timestamptz('deleted_at'),
    createdAt: createdAt(),
  },
  (t) => [index('chat_messages_created_at_idx').on(t.createdAt)],
);

/**
 * Web Push subscriptions: one per browser / installed app. The endpoint is
 * unique; signing in with another account on the same device moves it.
 */
export const pushSubscriptions = pgTable(
  'push_subscriptions',
  {
    endpoint: text('endpoint').primaryKey(),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    p256dh: text('p256dh').notNull(),
    auth: text('auth').notNull(),
    createdAt: createdAt(),
  },
  (t) => [index('push_subscriptions_user_idx').on(t.userId)],
);

/** Key/value store for club settings (see `clubSettingsSchema`). */
export const settings = pgTable('settings', {
  key: text('key').primaryKey(),
  value: jsonb('value').notNull(),
  updatedAt: updatedAt(),
});

export type UserRow = typeof users.$inferSelect;
export type PaymentRow = typeof payments.$inferSelect;
export type MeetupRow = typeof meetups.$inferSelect;
export type AnnouncementRow = typeof announcements.$inferSelect;
export type ClubPlaceRow = typeof clubPlaces.$inferSelect;
